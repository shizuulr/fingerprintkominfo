/** Helper: get semua desa flat */
export const getAllDesa = () => KECAMATAN_DESA.flatMap(k => k.desa);

/** Helper: get desa berdasarkan kecamatan ID */
export const getDesaByKecamatan = (kecamatanId) => {
  const kec = KECAMATAN_DESA.find(k => k.id === kecamatanId);
  return kec ? kec.desa : [];
};

/** Helper: get nama kecamatan dari ID desa */
export const getKecamatanByDesaId = (desaId) => {
  for (const kec of KECAMATAN_DESA) {
    if (kec.desa.some(d => d.id === desaId)) return kec;
  }
  return null;
};
